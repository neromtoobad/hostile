// Copies contract ABIs from contracts/out (after `forge build`) into src/abi.
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../contracts/out/", import.meta.url);
for (const [file, name] of [["League.sol", "League"], ["LeagueFactory.sol", "LeagueFactory"], ["LeagueCoins.sol", "LeagueCoins"]]) {
  const { abi } = JSON.parse(readFileSync(new URL(`${file}/${name}.json`, root), "utf8"));
  writeFileSync(new URL(`../src/abi/${name}.ts`, import.meta.url), `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(abi, null, 1)} as const;\n`);
  console.log("abi", name, abi.length);
}
