// Packs the card fonts (src/share/fonts/*.woff, Funnel Display and Funnel Sans, SIL Open Font
// License) into src/share/fonts.ts as base64, so the card function carries its fonts with it and
// never has to fetch them. Run after changing a font:  node scripts/og-fonts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const FONTS = [
  ["Funnel Display", 500, "FunnelDisplay-500.woff"],
  ["Funnel Display", 700, "FunnelDisplay-700.woff"],
  ["Funnel Sans", 400, "FunnelSans-400.woff"],
  ["Funnel Sans", 600, "FunnelSans-600.woff"],
];
const dir = new URL("../src/share/fonts/", import.meta.url);
const rows = FONTS.map(([name, weight, file]) => `  { name: "${name}", weight: ${weight}, base64: "${readFileSync(new URL(file, dir)).toString("base64")}" },`);
writeFileSync(
  new URL("../src/share/fonts.ts", import.meta.url),
  `// Generated by scripts/og-fonts.mjs from src/share/fonts/*.woff. Do not edit by hand.\nexport const FONT_FILES = [\n${rows.join("\n")}\n] as const;\n`,
);
console.log(`wrote src/share/fonts.ts (${FONTS.length} fonts)`);
